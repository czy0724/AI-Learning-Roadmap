"""
KNN算法介绍(K Nearest Neighbors),k近邻算法
   原理：
      基于 欧式距离 (或者其它距离计算方式) 计算 测试集 和 每个训练集之间的距离，然后根据距离升序排列，找到最近的 K 个样本。
      基于 K 个样本投票，票数多的就作为最终预测结果 → 分类问题。
      基于 K 个样本计算平均值，作为最终预测结果 → 回归问题。
   实现思路：
      1.分类问题
        适用于：有特征，有标签，且标签是不连续的 (离散的)
      2.回归问题。
         适用于：有特征，有标签，且标签是连续的。
   KNN 算法，分类问题思路如下：
   1.计算测试集和每个训练的样本之间的 距离。
   2.基于距离进行升序排列。
   3.找到最近的 K 个样本。
   4.K 个样本进行投票。
   5.票数多的结果，作为最终的预测结果。
   代码实现思路：
      1.导包。
      2.准备数据集 (测试集 和 训练集)
      3.创建 (KNN 分类模型) 模型对象。
      4.模型训练。
      5.模型预测。


"""
# 1.导包。
from sklearn.neighbors import KNeighborsClassifier

# 2.准备数据集 (测试集 和 训练集)

x_train = [[0], [1], [2], [3]]  # 训练集特征,因为特征可以有多个,所以这里用二维列表表示
y_train = [0, 0, 1, 1]  # 训练集标签,因为标签是离散的,所以这里是一维数组表示
x_test = [[5]]  # 测试集特征




# 3.创建 (KNN 分类模型) 模型对象。
#estimator 是估计器，用于估计参数
#neighbors 是最近邻的数量,默认是5
estimator = KNeighborsClassifier(n_neighbors=2)

# 4.模型训练。
#fit 是拟合，即训练模型,传入训练集特征和训练集标签
estimator.fit(x_train, y_train)


# 5.模型预测。
#predict 是预测，即用训练好的模型进行预测,传入测试集特征
y_pred = estimator.predict(x_test)


# 打印预测结果。
print("预测结果为：", y_pred)



























