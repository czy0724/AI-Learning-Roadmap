"""
特征预处理之标准化操作

回顾: 特征工程的目的 和 步骤
目的:
    利用专业的背景知识 和 技巧处理数据, 用于提升 模型的性能。
步骤:
    1. 特征提取。
    2. 特征预处理(归一化, 标准化)
    3. 特征降维。
    4. 特征选择。
    5. 特征组合。

特征预处理之 标准化介绍:
目的:
    防止因为量纲(单位)问题, 导致特征列的方差值相差较大, 影响模型的最终结果。
    所以通过公式把各列的值映射到 均值为0,标准差为1的正态分布序列
公式:
    x' = (当前值 - 该列均值) / (该列标准差 )

应用场景：
    适用于 大数据集 的处理。

结论：
    无论是归一化，还是标准化，目的都是为了解决因为量纲(单位)问题，导致模型评估较低等问题。

"""

#导包
from sklearn.preprocessing import StandardScaler#标准化

#1.准备数据集(标准化原始数据)
x_train = [[90,2,10,40],[60,4,15,45],[75,3,13,46]]

#2.创建标准化对象
# feature_range=(0,1) 表示把数据映射到 [0,1] 区间
transfer = StandardScaler()

#3.对原始数据集进行标准化操作
x_train_new = transfer.fit_transform(x_train)

#4.打印数据
print("标准化后的数据为：\n",x_train_new)

#5.打印数据集均值和方差
print("数据集的均值为：\n",transfer.mean_)
print("数据集的方差为：\n",transfer.var_)
print("数据集的标准差为：\n",transfer.std_)
